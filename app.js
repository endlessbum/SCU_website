                var atTop = panel.scrollTop <= 0;
                var atBottom = panel.scrollTop >= maxScroll - 1;

                // Не отдаём overscroll панели корневой странице.
                if ((dy > 0 && atTop) || (dy < 0 && atBottom)) {
                    e.preventDefault();
                }
